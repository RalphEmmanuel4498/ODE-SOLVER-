"""
Padé Approximant & Series Acceleration Module
=============================================

Implements [M/N] Padé approximants for power series generated by ADM, HPM, HAM, DTM, or Taylor expansions.
A Padé approximant is a rational function:
    [M/N](t) = P_M(t) / Q_N(t) = (p_0 + p_1*t + ... + p_M*t^M) / (1 + q_1*t + ... + q_N*t^N)
such that its Taylor expansion matches the given power series:
    f(t) = c_0 + c_1*t + c_2*t^2 + ... + c_{M+N}*t^{M+N} + O(t^{M+N+1})

Padé approximants are essential in semi-analytical applied mathematics because they:
1. Overcome finite radii of convergence caused by non-physical or complex poles.
2. Approximate unbounded or asymptotic limits as t -> infinity.
3. Eliminate secular terms in perturbation expansions.
"""

from typing import List, Tuple, Dict, Any, Optional
import numpy as np
import sympy as sp


def compute_pade_coefficients(
    coefficients: List[float],
    m: int,
    n: int
) -> Tuple[List[float], List[float], str]:
    """
    Given power series coefficients c_0, c_1, ..., c_{m+n},
    computes the numerator coefficients p_0, ..., p_m and
    denominator coefficients q_0(=1), q_1, ..., q_n.
    Returns (p, q, latex_representation).
    """
    total_order = m + n
    c = list(coefficients)
    if len(c) < total_order + 1:
        # Pad with zeros if necessary
        c = c + [0.0] * (total_order + 1 - len(c))

    # Setup linear system for q:
    # For j = m+1, m+2, ..., m+n:
    # sum_{k=1}^n c_{j-k} * q_k = -c_j
    if n > 0:
        A = np.zeros((n, n), dtype=float)
        b = np.zeros(n, dtype=float)
        for row, j in enumerate(range(m + 1, m + n + 1)):
            b[row] = -c[j]
            for col, k in enumerate(range(1, n + 1)):
                idx = j - k
                if 0 <= idx < len(c):
                    A[row, col] = c[idx]
                else:
                    A[row, col] = 0.0

        try:
            q_tail = np.linalg.solve(A, b)
            q = [1.0] + list(q_tail)
        except np.linalg.LinAlgError:
            # Fallback to pseudo-inverse or lower order
            q_tail = np.linalg.pinv(A) @ b
            q = [1.0] + list(q_tail)
    else:
        q = [1.0]

    # Compute p_0, ..., p_m:
    # p_j = sum_{k=0}^{\min(j, n)} c_{j-k} * q_k
    p = []
    for j in range(m + 1):
        pj = 0.0
        for k in range(min(j, n) + 1):
            pj += c[j - k] * q[k]
        p.append(pj)

    # Build LaTeX string
    t = sp.Symbol('t', real=True)
    num_poly = sum(p[i] * (t ** i) for i in range(len(p)))
    den_poly = sum(q[j] * (t ** j) for j in range(len(q)))

    num_latex = sp.latex(sp.nsimplify(num_poly, tolerance=1e-4))
    den_latex = sp.latex(sp.nsimplify(den_poly, tolerance=1e-4))

    latex_str = rf"\frac{{{num_latex}}}{{{den_latex}}}"
    return p, q, latex_str


def evaluate_pade(
    p: List[float],
    q: List[float],
    t_eval: np.ndarray,
    singularity_clip: float = 1e6
) -> np.ndarray:
    """
    Safely evaluate P_m(t) / Q_n(t) across t_eval array.
    """
    numerator = np.zeros_like(t_eval, dtype=float)
    for i, coeff in enumerate(p):
        numerator += coeff * (t_eval ** i)

    denominator = np.zeros_like(t_eval, dtype=float)
    for j, coeff in enumerate(q):
        denominator += coeff * (t_eval ** j)

    # Protect against pole division by zero
    mask = np.abs(denominator) < 1e-9
    safe_den = np.where(mask, 1e-9 * np.sign(denominator + 1e-12), denominator)
    result = numerator / safe_den
    result = np.clip(result, -singularity_clip, singularity_clip)
    return result
